//! The GENERATED contract table: the method ordinals and the interface type
//! ids, read from the **same** `CodeGeneratorRequest` the codegen consumed.
//!
//! Why this exists: a service that publishes a registry (cli.capnp's
//! `CommandRegistration`) names the method but the contract has no field for
//! its **ordinal** — and a client that never compiled the schema cannot
//! address the method without it. The engine therefore publishes the ordinal
//! it resolved from the schema tree, and the ordinal it publishes is the
//! compiler's own `codeOrder` — never a constant written by hand.
//!
//! The same artifact also yields the interface **type id** (the id of the
//! interface's schema node), so the registry and the router agree on which
//! interface a command names without either of them carrying a literal.
//!
//! The output (`OUT_DIR/contract.rs`) is deterministic: same request in, same
//! bytes out.

use std::collections::BTreeMap;
use std::fmt::Write as _;

/// One interface, with the methods it declares.
struct InterfaceEntry {
    /// The schema stem the interface lives in ("network").
    stem: String,
    /// The interface's name, as the schema spells it ("Network").
    name: String,
    /// The interface's type id (the id of its schema node).
    type_id: u64,
    /// The methods, with the ordinal the schema declares.
    methods: Vec<(String, u16)>,
}

/// Render the contract table from the request.
pub fn render(request: &capnp::schema_capnp::code_generator_request::Reader<'_>) -> String {
    let entries = collect(request);
    let files = collect_files(request);

    let mut method_arms = String::new();
    let mut interface_arms = String::new();
    for entry in &entries {
        let list = entry
            .methods
            .iter()
            .map(|(name, ordinal)| format!("(\"{name}\", {ordinal})"))
            .collect::<Vec<_>>()
            .join(", ");
        method_arms.push_str(&format!(
            "        (\"{}\", \"{}\") => &[{list}],\n",
            entry.stem, entry.name
        ));
        interface_arms.push_str(&format!(
            "        (\"{}\", \"{}\") => Some(0x{:x}),\n",
            entry.stem, entry.name, entry.type_id
        ));
    }
    let mut file_arms = String::new();
    for (id, stem) in &files {
        file_arms.push_str(&format!("        0x{id:x} => Some(\"{stem}\"),\n"));
    }

    let mut out = String::new();
    out.push_str("// @generated by build.rs — DO NOT EDIT.\n");
    out.push_str("//\n");
    out.push_str("// The contract's method ordinals and interface type ids, read from the\n");
    out.push_str("// CodeGeneratorRequest the codegen consumed. Nothing here is hand-written:\n");
    out.push_str("// a method's ordinal is the compiler's own `codeOrder`.\n\n");
    out.push_str("pub mod contract {\n");
    out.push_str("    /// The methods of a contract interface: the name the schema spells it\n");
    out.push_str("    /// and the capnp METHOD ID (the declared ordinal) it carries.\n");
    out.push_str(
        "    pub fn methods_of(stem: &str, interface: &str) -> &'static [(&'static str, u16)] {\n",
    );
    out.push_str("        match (stem, interface) {\n");
    out.push_str(&method_arms);
    out.push_str("            _ => &[],\n");
    out.push_str("        }\n");
    out.push_str("    }\n\n");
    out.push_str("    /// The capnp method id of one method of one interface.\n");
    out.push_str(
        "    pub fn method_id(stem: &str, interface: &str, method: &str) -> Option<u16> {\n",
    );
    out.push_str("        methods_of(stem, interface)\n");
    out.push_str("            .iter()\n");
    out.push_str("            .find(|(name, _)| *name == method)\n");
    out.push_str("            .map(|(_, id)| *id)\n");
    out.push_str("    }\n\n");
    out.push_str("    /// The capnp INTERFACE TYPE ID of one interface of one schema.\n");
    out.push_str("    pub fn interface_id(stem: &str, interface: &str) -> Option<u64> {\n");
    out.push_str("        match (stem, interface) {\n");
    out.push_str(&interface_arms);
    out.push_str("            _ => None,\n");
    out.push_str("        }\n");
    out.push_str("    }\n\n");
    out.push_str("    /// The schema stem a canonical schema id names.\n");
    out.push_str("    pub fn stem_for_schema_id(id: u64) -> Option<&'static str> {\n");
    out.push_str("        match id {\n");
    out.push_str(&file_arms);
    out.push_str("            _ => None,\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    let _ = writeln!(out);
    out
}

/// Collect every schema file's id and stem.
fn collect_files(
    request: &capnp::schema_capnp::code_generator_request::Reader<'_>,
) -> Vec<(u64, String)> {
    let mut files = Vec::new();
    let Ok(nodes) = request.get_nodes() else {
        return files;
    };
    for node in nodes.iter() {
        let Ok(capnp::schema_capnp::node::File(_)) = node.which() else {
            continue;
        };
        // A file node's display name is the file's path.
        let name = node
            .get_display_name()
            .map(|text| String::from_utf8_lossy(text.as_bytes()).into_owned())
            .unwrap_or_default();
        let stem = name
            .rsplit('/')
            .next()
            .unwrap_or(&name)
            .strip_suffix(".capnp")
            .unwrap_or(&name)
            .to_string();
        files.push((node.get_id(), stem));
    }
    files.sort_by(|a, b| a.0.cmp(&b.0));
    files
}

/// Walk the request's nodes and collect every interface with its methods.
fn collect(request: &capnp::schema_capnp::code_generator_request::Reader<'_>) -> Vec<InterfaceEntry> {
    let mut entries: BTreeMap<(String, String), InterfaceEntry> = BTreeMap::new();
    let Ok(nodes) = request.get_nodes() else {
        return Vec::new();
    };
    for node in nodes.iter() {
        let Ok(capnp::schema_capnp::node::Interface(interface)) = node.which() else {
            continue;
        };
        let display = node
            .get_display_name()
            .map(|text| String::from_utf8_lossy(text.as_bytes()).into_owned())
            .unwrap_or_default();
        let Some((stem, name)) = split_interface(&display) else {
            continue;
        };
        let mut methods = Vec::new();
        if let Ok(list) = interface.get_methods() {
            for method in list.iter() {
                let method_name = method
                    .get_name()
                    .map(|text| String::from_utf8_lossy(text.as_bytes()).into_owned())
                    .unwrap_or_default();
                methods.push((method_name, method.get_code_order()));
            }
        }
        methods.sort_by(|a, b| a.1.cmp(&b.1).then_with(|| a.0.cmp(&b.0)));
        entries.insert(
            (stem.clone(), name.clone()),
            InterfaceEntry {
                stem,
                name,
                type_id: node.get_id(),
                methods,
            },
        );
    }
    entries.into_values().collect()
}

/// Split an interface's display name into (schema stem, interface name).
///
/// The compiler's display name is `<file>:<Interface>` ("network.capnp:Network")
/// and the prefix length tells where the simple name starts; the file's stem
/// is the schema's own name.
fn split_interface(display: &str) -> Option<(String, String)> {
    let (file, name) = display.split_once(':')?;
    if file.is_empty() || name.is_empty() || name.contains('.') {
        return None;
    }
    let stem = file.strip_suffix(".capnp").unwrap_or(file);
    Some((stem.to_string(), name.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_interface_display_name_splits_into_stem_and_name() {
        assert_eq!(
            split_interface("network.capnp:Network"),
            Some(("network".to_string(), "Network".to_string()))
        );
        assert_eq!(split_interface("Network"), None);
        assert_eq!(split_interface("network.capnp:Outer.Inner"), None);
    }
}
