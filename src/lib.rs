#![no_std]
//! smart-lib — protocol-compliant backends for common operating systems.
//!
//! One library, every altitude (charter law #1): the core is `no_std` +
//! `alloc`, so the same API links into a kernel module, a service or an app.
//! The `std` feature only widens the dependency graph; it never changes the
//! core's shape.
//!
//! ## Module registration pattern (read this before adding a domain)
//!
//! A domain is added by creating exactly one file and one manifest line — and
//! by editing **no shared file**:
//!
//! 1. `src/domains/<stem>.rs` (or `src/domains/<stem>/mod.rs`) — the domain's
//!    hand-written backends, owned solely by that domain's agent.
//! 2. one line in `Cargo.toml`: `domain-<stem-with-dashes> = []` — owned by the
//!    orchestrator's wire agent.
//!
//! That is the whole change. `build.rs` (feature = domain, law #2) resolves
//! `domain-<stem>` to `schema/<stem-with-underscores>.capnp`, compiles the
//! transitive closure of the *enabled* schemas, and emits a generated module
//! tree in `OUT_DIR` which is included below. `src/lib.rs` therefore never
//! changes when a domain is added, and domain agents can never conflict on a
//! shared file.
//!
//! The generated tree has two halves, both driven by the same feature names:
//!
//! ```text
//! pub mod schema  {        // capnp codegen, one module per compiled schema
//!     pub mod types_capnp       { include!(.../types_capnp.rs) }
//!     pub mod capability_capnp  { ... }          // foundation: always present
//!     pub mod files_capnp       { ... }          // only if domain-files is on
//!     pub mod network_capnp     { ... }          // only if domain-network is on
//! }
//! pub mod domains {         // hand-written glue, one module per enabled domain
//!     #[path = ".../src/domains/files.rs"] pub mod files;
//! }
//! ```
//!
//! Cross-file references inside the generated code resolve as
//! `crate::schema::<stem>_capnp::…` because build.rs passes
//! `default_parent_module(["schema"])` to capnpc.
//!
//! Ownership is enforced by that split: `src/domains/**` and
//! `src/platforms/**` are per-domain files; `src/core/**` (law #3: the
//! object-safe per-domain backend traits), `src/transport/**` (law #4) and
//! `src/conformance/**` belong to their own waves. This file, `Cargo.toml`,
//! `build.rs`, `src/prelude.rs` and `src/codegen/**` are the skeleton agent's.
#![warn(missing_docs)]

